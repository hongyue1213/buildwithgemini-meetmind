"""Image generation tools for MeetMind agent using gemini-3.1-flash-lite-image."""
import datetime
import uuid
from typing import Any, Dict
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

PROJECT_ID = "qwiklabs-gcp-03-8581f7539bcb"
BUCKET_NAME = "meetmind-assets-qwiklabs-gcp-03-8581f7539bcb"

_genai_client = None
_storage_client = None


def _get_genai_client() -> genai.Client:
    global _genai_client
    if _genai_client is None:
        _genai_client = genai.Client(vertexai=True, project=PROJECT_ID, location="global")
    return _genai_client


def _get_storage_client() -> storage.Client:
    global _storage_client
    if _storage_client is None:
        _storage_client = storage.Client(project=PROJECT_ID)
    return _storage_client


async def generate_meeting_visual(
    prompt: str,
    title: str = "meeting_visual",
    tool_context: ToolContext = None,
) -> Dict[str, Any]:
    """Generates a visual summary, mind map, or diagram for a meeting or milestone.

    Uses gemini-3.1-flash-lite-image in the global region. Saves the image as an ADK session artifact
    and uploads the image bytes directly to the public Cloud Storage bucket without writing to local disk.

    Args:
        prompt: Description of the diagram, visual mind map, or illustration to generate.
        title: Short title or topic slug for the image filename (e.g. 'ai_roadmap_mindmap').
        tool_context: ADK ToolContext injected by the framework.

    Returns:
        A dictionary with the public HTTPS URL, artifact filename, and status.
    """
    try:
        client = _get_genai_client()

        full_prompt = f"Professional clean infographic illustration for a team meeting: {prompt}"

        response = client.models.generate_content(
            model="gemini-3.1-flash-lite-image",
            contents=full_prompt,
            config=types.GenerateContentConfig(
                response_modalities=["IMAGE"],
                image_config=types.ImageConfig(
                    aspect_ratio="1:1",
                    image_size="1K",
                ),
            ),
        )

        image_bytes = None
        mime_type = "image/png"

        for candidate in response.candidates:
            if candidate.content and candidate.content.parts:
                for part in candidate.content.parts:
                    if part.inline_data:
                        image_bytes = part.inline_data.data
                        mime_type = part.inline_data.mime_type or "image/png"
                        break
            if image_bytes:
                break

        if not image_bytes:
            return {"status": "error", "message": "No image data was generated by the model."}

        slug = "".join(c for c in title.lower() if c.isalnum() or c in ("-", "_")).strip("-_") or "visual"
        ext = "png" if "png" in mime_type.lower() else "jpg"
        timestamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d_%H%M%S")
        filename = f"{slug}_{timestamp}_{uuid.uuid4().hex[:6]}.{ext}"

        # 1. Save with tool_context.save_artifact for Playground Artifacts panel
        artifact_saved = False
        artifact_version = None
        if tool_context is not None:
            artifact_part = types.Part.from_bytes(data=image_bytes, mime_type=mime_type)
            artifact_version = await tool_context.save_artifact(
                filename=filename,
                artifact=artifact_part,
            )
            artifact_saved = True

        # 2. Upload directly to public Cloud Storage bucket without local file write
        storage_cli = _get_storage_client()
        bucket = storage_cli.bucket(BUCKET_NAME)
        blob = bucket.blob(f"visuals/{filename}")
        blob.upload_from_string(image_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/visuals/{filename}"

        return {
            "status": "success",
            "public_url": public_url,
            "filename": filename,
            "artifact_saved": artifact_saved,
            "artifact_version": artifact_version,
            "message": f"Successfully generated meeting visual and uploaded to {public_url}",
        }
    except Exception as e:
        return {"status": "error", "message": f"Failed to generate meeting visual: {str(e)}"}

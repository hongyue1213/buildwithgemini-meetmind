"""Video generation tools for MeetMind agent using gemini-omni-flash-preview."""
import base64
import datetime
import uuid
from typing import Any, Dict
from google import genai
from google.genai import types
from google.cloud import storage
from google.adk.tools import ToolContext

PROJECT_ID = "qwiklabs-gcp-03-8581f7539bcb"
BUCKET_NAME = "meetmind-assets-qwiklabs-gcp-03-8581f7539bcb"

_genai_client = None
_storage_client = None


def _get_genai_client() -> genai.Client:
    global _genai_client
    if _genai_client is None:
        _genai_client = genai.Client(vertexai=True, project=PROJECT_ID, location="global")
    return _genai_client


def _get_storage_client() -> storage.Client:
    global _storage_client
    if _storage_client is None:
        _storage_client = storage.Client(project=PROJECT_ID)
    return _storage_client


async def generate_meeting_video(
    prompt: str,
    title: str = "meeting_video",
    tool_context: ToolContext = None,
) -> Dict[str, Any]:
    """Generates a short video for a meeting highlight, milestone celebration, or recap.

    Uses Google's Omni model (gemini-omni-flash-preview) in the global region via the Interactions API.
    Saves the video as an ADK session artifact and uploads the video bytes directly to the
    public Cloud Storage bucket without writing to local disk.

    Args:
        prompt: Description of the meeting highlight, milestone animation, or topic recap video to generate.
        title: Short title or topic slug for the video filename (e.g. 'q3_launch_celebration').
        tool_context: ADK ToolContext injected by the framework.

    Returns:
        A dictionary with the public HTTPS URL, artifact filename, and status.
    """
    try:
        client = _get_genai_client()

        full_prompt = f"Professional short animation for team meeting highlights: {prompt}"

        # gemini-omni-flash-preview is an Omni model accessed via client.interactions.create
        res = client.interactions.create(
            model="gemini-omni-flash-preview",
            input=full_prompt,
        )

        if not res or not res.output_video:
            return {"status": "error", "message": "No video was generated by the model."}

        raw_data = res.output_video.data
        if not raw_data:
            return {"status": "error", "message": "Video was generated but output data is empty."}

        if isinstance(raw_data, str):
            video_bytes = base64.b64decode(raw_data)
        elif isinstance(raw_data, bytes):
            video_bytes = raw_data
        else:
            video_bytes = bytes(raw_data)

        mime_type = res.output_video.mime_type or "video/mp4"

        slug = "".join(c for c in title.lower() if c.isalnum() or c in ("-", "_")).strip("-_") or "video"
        ext = "mp4" if "mp4" in mime_type.lower() else "webm"
        timestamp = datetime.datetime.now(datetime.timezone.utc).strftime("%Y%m%d_%H%M%S")
        filename = f"{slug}_{timestamp}_{uuid.uuid4().hex[:6]}.{ext}"

        # 1. Save with tool_context.save_artifact for Playground Artifacts panel
        artifact_saved = False
        artifact_version = None
        if tool_context is not None:
            artifact_part = types.Part.from_bytes(data=video_bytes, mime_type=mime_type)
            artifact_version = await tool_context.save_artifact(
                filename=filename,
                artifact=artifact_part,
            )
            artifact_saved = True

        # 2. Upload directly to public Cloud Storage bucket without local file write
        storage_cli = _get_storage_client()
        bucket = storage_cli.bucket(BUCKET_NAME)
        blob = bucket.blob(f"videos/{filename}")
        blob.upload_from_string(video_bytes, content_type=mime_type)

        public_url = f"https://storage.googleapis.com/{BUCKET_NAME}/videos/{filename}"

        return {
            "status": "success",
            "public_url": public_url,
            "filename": filename,
            "artifact_saved": artifact_saved,
            "artifact_version": artifact_version,
            "message": f"Successfully generated meeting video and uploaded to {public_url}",
        }
    except Exception as e:
        return {"status": "error", "message": f"Failed to generate meeting video: {str(e)}"}
